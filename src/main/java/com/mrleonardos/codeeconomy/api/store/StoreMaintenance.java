package com.mrleonardos.codeeconomy.api.store;

import java.util.Map;
import java.util.UUID;

import com.mrleonardos.codeeconomy.api.model.AccountView;

/**
 * Обслуживание носителя: снимок по требованию, сверка и снятие карантина.
 *
 * <p>
 * Необязательная часть SPI. Её реализует провайдер, у которого состояние живёт в двух местах и они
 * могут разъехаться: встроенный {@code json} держит чекпоинт отдельно от журнала, поэтому умеет и
 * снимок, и сверку. Провайдеру поверх базы данных, где {@code apply} уже фиксирует транзакцию,
 * реализовывать нечего, и движок его об этом не спрашивает.
 *
 * <p>
 * Движок узнаёт умение по {@code instanceof} у активного провайдера. Пока провайдер его не заявил,
 * {@code /eco checkpoint} уходит в {@link EconomyStore#save(StoreSnapshot)}, а {@code /eco verify}
 * сверяет журнал по кольцевой истории в памяти.
 */
public interface StoreMaintenance {

    /**
     * Записать снимок сейчас.
     *
     * @param state состояние движка целиком: счета и граница, которую они покрывают
     * @return записан ли файл и до какой записи доведён чекпоинт
     */
    CheckpointResult checkpoint(StoreSnapshot state);

    /**
     * Сверить счета с носителем.
     *
     * <p>
     * Работает из фонового потока, поэтому границу {@code upToSeq} снимают вместе со счетами: записи
     * свежее неё легли на носитель уже после снимка и расхождением не считаются.
     *
     * @param accounts счета движка на момент снятия границы
     * @param upToSeq  наибольший {@code seq}, учтённый в этих счетах
     */
    StoreVerification verify(Map<UUID, AccountView> accounts, long upToSeq);

    /**
     * Снять с носителя признак карантина.
     *
     * <p>
     * Признак ставится сам, когда носитель поднялся после аварии, и держит мод в режиме только для
     * чтения через любое число перезапусков. Снимает его администратор, разобравшись с потерей.
     */
    StoreResult liftReadOnly();
}
