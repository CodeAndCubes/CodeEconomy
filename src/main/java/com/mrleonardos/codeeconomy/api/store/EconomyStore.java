package com.mrleonardos.codeeconomy.api.store;

/**
 * Хранилище денег: точка расширения для чужих провайдеров.
 *
 * <p>
 * Встроенный провайдер {@code json} держит чекпоинт {@code accounts.json} и append-only журнал
 * {@code journal.jsonl}. Чужой мод регистрирует свою реализацию в {@code EconomyApi}, а выбирается он
 * по имени из настройки {@code storage.provider}. Провайдер работает с готовыми счетами и записями и
 * не знает, откуда пришла мутация.
 *
 * <p>
 * Контракт {@link #apply}: возврат из метода означает, что пачка записана на носителе. Отказ это
 * {@link StoreResult} с причиной, после него мод встаёт в режим деградации и операция вызывающему не
 * засчитывается, он повторит её сам. Очереди неподтверждённых операций у провайдера быть не должно:
 * операция, которой нет на носителе, денег не создаёт.
 */
public interface EconomyStore {

    /** Имя провайдера, по нему его выбирает настройка {@code storage.provider}. */
    String id();

    /** Прочитать состояние целиком: чекпоинт плюс записи журнала после него. */
    StoreSnapshot load();

    /**
     * Применить пачку одного коммита. Частичного применения нет: провайдер либо записывает всё, либо
     * отвечает отказом и оставляет носитель в прежнем состоянии.
     */
    StoreResult apply(ChangeBatch batch);

    /**
     * Записать состояние целиком.
     *
     * <p>
     * Провайдеру, который ведёт учёт по {@link #apply}, полная выгрузка не нужна, поэтому по умолчанию
     * метод отвечает отказом {@code UNSUPPORTED}. Провайдеры с полной выгрузкой, например мосты в базы
     * данных, переопределяют его.
     */
    default StoreResult save(StoreSnapshot snapshot) {
        return StoreResult.failure(StoreResult.Failure.UNSUPPORTED, "save is not supported by " + id());
    }
}
