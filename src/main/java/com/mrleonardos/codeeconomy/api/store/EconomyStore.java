package com.mrleonardos.codeeconomy.api.store;

/**
 * Хранилище денег: точка расширения для чужих провайдеров.
 *
 * <p>
 * Встроенный провайдер {@code json} держит чекпоинт {@code economy-accounts.json} и append-only журнал
 * {@code economy-journal.jsonl} в папке мира. Чужой мод регистрирует свою реализацию в
 * {@code EconomyApi}, а выбирается она по имени из {@code [storage] provider} главного файла. Провайдер работает с
 * готовыми счетами и записями и
 * не знает, откуда пришла мутация.
 *
 * <p>
 * Контракт {@link #apply}: возврат из метода означает, что пачка записана на носителе. Отказ это
 * {@link StoreResult} с причиной, после него мод встаёт в режим деградации и операция вызывающему не
 * засчитывается, он повторит её сам. Очереди неподтверждённых операций у провайдера быть не должно:
 * операция, которой нет на носителе, денег не создаёт.
 */
public interface EconomyStore {

    /** Имя провайдера, по нему его выбирает ключ {@code [storage] provider} главного файла. */
    String id();

    /** Прочитать состояние целиком: чекпоинт плюс записи журнала после него. */
    StoreSnapshot load();

    /**
     * Применить пачку одного коммита. Частичного применения нет: провайдер либо записывает всё, либо
     * отвечает отказом и оставляет носитель в прежнем состоянии.
     *
     * <p>
     * Пачка без записей журнала это правка счёта без движения денег: отметка последнего ника, заморозка.
     * Записывать её в журнал нечем и незачем, провайдеру достаточно принять новые версии счетов.
     */
    StoreResult apply(ChangeBatch batch);

    /**
     * Записать состояние целиком.
     *
     * <p>
     * Полная выгрузка: после успешного ответа носитель обязан держать ровно
     * {@link StoreSnapshot#accounts()} с границей {@link StoreSnapshot#lastSeq()}, а не разницу с
     * прежним содержимым. На этом стоит {@code /eco compact}: провайдер вправе выбросить всё, что
     * старше границы, только когда снимок записан целиком.
     *
     * <p>
     * Провайдеру, который ведёт учёт по {@link #apply}, полная выгрузка не нужна, поэтому по умолчанию
     * метод отвечает отказом {@code UNSUPPORTED}. Провайдеры с полной выгрузкой, например мосты в базы
     * данных, переопределяют его.
     */
    default StoreResult save(StoreSnapshot snapshot) {
        return StoreResult.failure(StoreResult.Failure.UNSUPPORTED, "save is not supported by " + id());
    }

    /**
     * Отпустить носитель: сервер останавливается, новых записей не будет.
     *
     * <p>
     * Файловому провайдеру здесь закрывать дескриптор, мосту в базу отпускать соединение. Отказ не
     * поднимается наверх: сервер всё равно останавливается, и падать на этом незачем.
     */
    default void close() {}
}
