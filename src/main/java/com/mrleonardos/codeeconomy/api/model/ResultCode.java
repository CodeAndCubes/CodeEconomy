package com.mrleonardos.codeeconomy.api.model;

/**
 * Конечный перечень исходов мутации.
 *
 * <p>
 * Перечень закрытый: чужой мод получает только его и потому разбирает результат без загадочных
 * значений. Новый способ отказа это правка перечня, а не новая строка в логе.
 */
public enum ResultCode {

    /** Операция проведена. */
    OK,

    /** Такой {@code transactionId} уже проведён, возвращён записанный исход. */
    DUPLICATE,

    /** У отправителя не хватает денег с учётом {@code minBalance}. */
    INSUFFICIENT,

    /** Получатель вышел бы за {@code maxBalance}. */
    ABOVE_CEILING,

    /** Итоговый баланс ушёл бы ниже пола счёта. */
    BELOW_FLOOR,

    /** Сумма не подходит: ноль, отрицательная там, где это запрещено, или не разобралась. */
    BAD_AMOUNT,

    /** Валюты с таким идентификатором нет. */
    UNKNOWN_CURRENCY,

    /** Игрока нет ни в сети, ни в кэше профилей. */
    UNKNOWN_PLAYER,

    /** Отправитель и получатель это один счёт. */
    SAME_ACCOUNT,

    /** Валюта закрыта для переводов между игроками. */
    PAY_DISABLED,

    /** Счёт заморожен, движение закрыто в обе стороны. */
    ACCOUNT_FROZEN,

    /** Один из {@code TransferGuard} отказал. */
    GUARD_VETO,

    /** Хранилище не смогло записать, операция целиком не состоялась. */
    STORE_FAILURE,

    /** Мод поднят только для чтения, мутации закрыты. */
    READONLY,

    /** Запрос не заполнен или не вписывается в потолки. */
    INVALID_REQUEST
}
