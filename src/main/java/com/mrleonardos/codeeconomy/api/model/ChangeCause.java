package com.mrleonardos.codeeconomy.api.model;

/**
 * Причина мутации денег. Видна в записях журнала и в аудите, по ней понятно, кто и зачем подвинул
 * баланс.
 */
public enum ChangeCause {

    /** Мутация из команды администратора или игрока. */
    COMMAND,

    /** Мутация через API чужого мода. */
    API,

    /** Перенос балансов из внешнего файла командой импорта. */
    IMPORT,

    /** Приведение состояния к новой версии схемы. */
    MIGRATION
}
