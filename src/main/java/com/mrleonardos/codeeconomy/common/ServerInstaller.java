package com.mrleonardos.codeeconomy.common;

/**
 * Серверная половина мода с точки зрения общего кода.
 *
 * <p>
 * Общий код не знает ни одного серверного класса: он видит только этот интерфейс, а реализация
 * подставляется по имени класса. Иначе клиентский jar, из которого деньги вырезаны целиком, не
 * загрузился бы вовсе.
 *
 * <p>
 * Порядок вызовов повторяет фазы FML: {@code init}, {@code postInit}, старт и остановка сервера.
 */
public interface ServerInstaller {

    /** Фаза init: объявить роль {@code economy} и обе заявки на неё. */
    void init();

    /** Фаза postInit: узнать владельца роли и собрать деньги, если роль осталась за нами. */
    void postInit();

    /** Сервер стартует: главный поток известен, мир открыт, состояние можно читать. */
    void serverStarting();

    /** Сервер останавливается: дописать чекпоинт и закрыть журнал. */
    void serverStopping();
}
